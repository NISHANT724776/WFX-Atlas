// The admin directory: a readable TXT file (knowledge/admin/users.txt) listing every account, rewritten whenever accounts change, and
// the same text indexed as passages of kind "admin_user" so an administrator can ask the assistant "who has the approver role?".
// It never contains passwords, password hashes, session tokens or setup tokens. Search hides these passages from everybody except
// an administrator (search() excludes the kind unless includeAdmin is set), so a viewer's question can never retrieve them.
import fs from 'node:fs';
import path from 'node:path';
import { settings } from '../config.ts';
import { all, run } from '../db.ts';
import { nowIso } from '../util.ts';

export const ADMIN_DIR = 'admin';
export const ADMIN_FILE = `${ADMIN_DIR}/users.txt`;
export const ADMIN_KIND = 'admin_user';

interface Row { id: number; username: string; display_name: string; role: string; disabled: number; pending: number; created_at: string }
const rows = () => all<Row>('SELECT id, username, display_name, role, disabled, pending, created_at FROM users ORDER BY role = \'admin\' DESC, username');
const status = (r: Row) => (r.pending ? 'pending approval' : r.disabled ? 'disabled' : 'active');
const roleText: Record<string, string> = { admin: 'everything, including users and settings', approver: 'approve and activate knowledge', editor: 'upload and draft knowledge', viewer: 'read and ask' };

/** One user as readable text (the unit that is written to the file and indexed). */
export const userBlock = (r: Row) => [
  `USER: ${r.username}`,
  `DISPLAY NAME: ${r.display_name}`,
  `ROLE: ${r.role} (${roleText[r.role] ?? ''})`,
  `STATUS: ${status(r)}`,
  `CREATED: ${r.created_at.slice(0, 10)}`,
].join('\n');

/** Rewrites knowledge/admin/users.txt from the accounts table and refreshes the admin-only passages in the search index. */
export function syncAdminDirectory(): { file: string; users: number } {
  const list = rows();
  const text = [
    '# WFX users and roles. Generated by the platform whenever an account is added, approved, changed or removed.',
    '# This file never contains passwords or any secret. Edit users in the app (Profile or Admin), not here: changes made to this file are overwritten.',
    `# Updated ${nowIso()}`,
    '',
    ...list.flatMap((r) => [userBlock(r), '='.repeat(80)]),
    '',
  ].join('\n');
  const file = path.join(settings().knowledge, ADMIN_DIR, 'users.txt');
  fs.mkdirSync(path.dirname(file), { recursive: true });
  fs.writeFileSync(file, text, 'utf8');
  // the same blocks, searchable by administrators only
  run('DELETE FROM chunks WHERE kind = ?', ADMIN_KIND);
  for (const r of list) {
    run(
      `INSERT INTO chunks (ref, kind, title, heading, text, module, txn, status, source_label, doc_id, doc_version, entry_id, entry_version, locator, is_current)
       VALUES (?, ?, ?, ?, ?, NULL, NULL, 'Active', ?, NULL, NULL, NULL, NULL, ?, 1)`,
      `admin:user:${r.id}`, ADMIN_KIND, `User ${r.username}`, 'Users and roles', userBlock(r), 'Admin directory (knowledge/admin/users.txt)', `user ${r.username}`,
    );
  }
  return { file: ADMIN_FILE, users: list.length };
}

/** The file as it is now (for the admin screen). */
export function readAdminDirectory(): { file: string; text: string } {
  const f = path.join(settings().knowledge, ADMIN_DIR, 'users.txt');
  if (!fs.existsSync(f)) syncAdminDirectory();
  return { file: ADMIN_FILE, text: fs.readFileSync(f, 'utf8') };
}
