// Builds src/app/shared/icon-data.ts from lucide-static (ISC), the interface icon set the taste skill uses.
// Each app icon name maps to one Lucide icon; the SVG elements are stored as shape lists so the app needs no
// runtime icon package. Run after changing the map:  node backend/scripts/build-icons.mjs
import fs from 'node:fs';
import path from 'node:path';

const ROOT = path.resolve(import.meta.dirname, '..', '..');
const SRC = path.join(ROOT, 'node_modules', 'lucide-static', 'icons');
const MAP = {
  // modules and data areas
  'mod-setup': 'sliders-horizontal', 'mod-style': 'shirt', 'mod-booking': 'calendar-check', 'mod-sales': 'receipt-text',
  'mod-planning': 'chart-gantt', 'mod-production': 'factory', 'mod-inventory': 'warehouse', 'mod-tna': 'calendar-clock',
  'mod-masters': 'database', 'mod-definitions': 'sigma',
  // workflow steps and actions
  swatch: 'palette', shirt: 'shirt', roll: 'cylinder', bom: 'file-spreadsheet', route: 'route', calc: 'calculator', check: 'badge-check',
  clipboard: 'clipboard-list', list: 'list', cube: 'box', gear: 'settings', table: 'table', save: 'save', play: 'circle-play', doc: 'file-text',
  cart: 'shopping-cart', truck: 'truck', box: 'package', order: 'receipt', link: 'link', scale: 'scale', chart: 'chart-column',
  factory: 'factory', cog: 'cog', user: 'user', bolt: 'zap', arrow: 'arrow-right', search: 'search',
};
const out = {};
for (const [name, lucide] of Object.entries(MAP)) {
  const file = path.join(SRC, `${lucide}.svg`);
  if (!fs.existsSync(file)) throw new Error(`lucide-static has no ${lucide}.svg (for ${name})`);
  const svg = fs.readFileSync(file, 'utf8');
  const els = [];
  for (const m of svg.matchAll(/<(path|circle|rect|line|polyline|polygon|ellipse)\s([^>]*?)\/?>/g)) {
    const attrs = Object.fromEntries([...m[2].matchAll(/([a-z-]+)="([^"]*)"/g)].map((a) => [a[1], a[2]]));
    els.push({ t: m[1], ...attrs });
  }
  out[name] = els;
}
const ts = `// Generated by backend/scripts/build-icons.mjs from lucide-static ${JSON.parse(fs.readFileSync(path.join(SRC, '..', 'package.json'), 'utf8')).version} (ISC licence). Do not edit by hand.
export type IconShape = { t: 'path' | 'circle' | 'rect' | 'line' | 'polyline' | 'polygon' | 'ellipse'; [attr: string]: string | undefined };
export const ICONS: Record<string, IconShape[]> = ${JSON.stringify(out)} as Record<string, IconShape[]>;
export const ICON_SOURCE: Record<string, string> = ${JSON.stringify(MAP)};
`;
fs.writeFileSync(path.join(ROOT, 'src', 'app', 'shared', 'icon-data.ts'), ts);
console.log(`${Object.keys(out).length} icons written`);
